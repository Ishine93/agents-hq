export const HAUTEUR_LIGNE = 10; // 7 + jambage 2 + 1 d'interligne

export function normaliser(s) {
  if (s == null) return '';
  let r = String(s).replace(/[…]/g, '…');
  r = r.normalize('NFD').replace(/[̀-ͯ]/g, '');
  let out = '';
  for (const ch of r) {
    if (G[ch]) out += ch;
    else if (REMPLACE[ch] !== undefined) out += REMPLACE[ch];
    else if (ch === '\n' || ch === '\r') out += ' ';
    else out += '?';
  }
  return out;
}

function largeurGlyphe(ch) {
  const g = G[ch] || G['?'];
  return g[0].length;
}

export function mesurer(s) {
  const t = normaliser(s);
  let w = 0;
  for (const ch of t) w += largeurGlyphe(ch) + 1;
  return Math.max(0, w - 1);
}

// Coupe un texte pour qu'il tienne en `max` pixels, avec « … » si besoin.
export function tronquer(s, max) {
  const t = normaliser(s);
  if (mesurer(t) <= max) return t;
  const ell = largeurGlyphe('…') + 1;
  let w = 0;
  let out = '';
  for (const ch of t) {
    const cw = largeurGlyphe(ch) + 1;
    if (w + cw + ell > max) break;
    out += ch;
    w += cw;
  }
  return out.replace(/\s+$/, '') + '…';
}

// Découpe en lignes de `max` pixels (au plus `nbMax` lignes, la dernière tronquée).
export function couperLignes(s, max, nbMax = 3) {
  const mots = normaliser(s).split(' ').filter(Boolean);
  const lignes = [];
  let cour = '';
  for (const m of mots) {
    const essai = cour ? cour + ' ' + m : m;
    if (mesurer(essai) <= max) {
      cour = essai;
    } else {
      if (cour) lignes.push(cour);
      cour = mesurer(m) > max ? tronquer(m, max) : m;
    }
  }
  if (cour) lignes.push(cour);
  if (lignes.length > nbMax) {
    const reste = lignes.slice(nbMax - 1).join(' ');
    lignes.length = nbMax - 1;
    lignes.push(tronquer(reste, max));
  }
  return lignes;
}

export function dessinerTexte(ctx, s, x, y, couleur) {
  const t = normaliser(s);
  ctx.fillStyle = couleur;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of t) {
    const g = G[ch] || G['?'];
    for (let r = 0; r < g.length; r++) {
      const row = g[r];
      for (let c = 0; c < row.length; c++) {
        if (row.charCodeAt(c) === 35) ctx.fillRect(cx + c, cy + r, 1, 1);
      }
    }
    cx += g[0].length + 1;
  }
  return cx - x - 1;
}

const cache = new Map();

// Rend un texte dans un petit canvas mis en cache. Option `ombre` : contour d'1 px.
export function texteCanvas(s, couleur, ombre = null) {
  const cle = s + '\u0001' + couleur + '\u0001' + (ombre || '');
  let c = cache.get(cle);
  if (c) return c;
  const w = Math.max(1, mesurer(s)) + (ombre ? 2 : 0);
  const h = 9 + (ombre ? 2 : 0);
  c = document.createElement('canvas');
  c.width = w;
  c.height = h;
  const g = c.getContext('2d');
  if (ombre) {
    for (const [dx, dy] of [[0, 1], [2, 1], [1, 0], [1, 2], [0, 0], [2, 0], [0, 2], [2, 2]]) {
      dessinerTexte(g, s, dx, dy, ombre);
    }
    dessinerTexte(g, s, 1, 1, couleur);
  } else {
    dessinerTexte(g, s, 0, 0, couleur);
  }
  if (cache.size > 1500) cache.clear();
  cache.set(cle, c);
  return c;
}
